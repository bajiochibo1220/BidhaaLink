function getMarketplaceSearchQuery() {
  const input = document.getElementById('businessSearch');
  const value = input?.value?.trim() || '';
  if (/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value)) {
    if (input) input.value = '';
    return '';
  }
  return value;
}

