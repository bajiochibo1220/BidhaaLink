function setupMarketplaceFeed() {
  setupMarketplacePaneToggles();
  setupCustomerPostComposer();
  const scroll = document.getElementById('marketplaceFeedScroll');
  const sentinel = document.getElementById('marketplaceFeedSentinel');
  const loadMore = document.getElementById('marketplaceFeedLoadMore');
  const refreshButtons = document.querySelectorAll('[data-refresh-feed]');
  if (!scroll) return;

  if ('IntersectionObserver' in window && sentinel) {
    marketplaceFeedObserver?.disconnect();
    marketplaceFeedObserver = new IntersectionObserver(entries => {
      if (entries.some(entry => entry.isIntersecting)) loadMarketplaceFeed();
    }, { root: scroll, rootMargin: '500px 0px', threshold: 0 });
    marketplaceFeedObserver.observe(sentinel);
  }
  if ('IntersectionObserver' in window) {
    marketplaceFeedVideoObserver?.disconnect();
    marketplaceFeedVideoObserver = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        const video = entry.target;
        if (entry.isIntersecting && entry.intersectionRatio >= 0.65) video.play().catch(() => {});
        else video.pause();
      });
    }, { root: scroll, rootMargin: '0px', threshold: [0, 0.65] });

    marketplaceFeedMediaObserver?.disconnect();
    marketplaceFeedMediaObserver = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        if (!entry.isIntersecting) return;
        const media = entry.target;
        if (media instanceof HTMLVideoElement && media.preload !== 'auto') {
          media.preload = 'auto';
          media.load();
        } else if (media instanceof HTMLImageElement && media.loading === 'lazy') {
          media.loading = 'eager';
          media.fetchPriority = 'high';
        }
        marketplaceFeedMediaObserver.unobserve(media);
      });
    }, { root: scroll, rootMargin: '120% 0px', threshold: 0.01 });
  }
  loadMore?.addEventListener('click', () => loadMarketplaceFeed());
  refreshButtons.forEach(button => button.addEventListener('click', () => loadMarketplaceFeed(true)));
}

