function redirectToPendingServiceConversation() {
  try {
    const pending = JSON.parse(localStorage.getItem('postLoginServiceConversation') || 'null');
    const pendingProduct = JSON.parse(localStorage.getItem('postLoginProductConversation') || 'null');
    const inquiry = pending || pendingProduct;
    if (!inquiry || typeof inquiry.businessSlug !== 'string' || !inquiry.businessSlug.trim()) return false;
    const currentSlug = String(window.businessSlug || '');
    if (window.businessProfileLoaded && currentSlug === inquiry.businessSlug) {
      if (pending && typeof window.resumePostLoginBusinessServiceConversation === 'function') {
        window.resumePostLoginBusinessServiceConversation();
        return true;
      }
      if (pendingProduct && typeof window.resumePendingProductInquiry === 'function') {
        window.resumePendingProductInquiry();
        return true;
      }
    }
    if (pendingProduct && !pending) {
      window.location.assign(`/business/${encodeURIComponent(inquiry.businessSlug)}?productInquiry=1`);
      return true;
    }
    window.location.assign(`/business/${encodeURIComponent(inquiry.businessSlug)}?serviceChat=1`);
    return true;
  } catch (_) {
    return false;
  }
}

function consumePostLoginReturn() {
  let destination = '';
  try {
    destination = localStorage.getItem('postLoginReturnTo') || '';
    localStorage.removeItem('postLoginReturnTo');
    const target = new URL(destination, window.location.origin);
    // Resume only known customer pages; storage is not a trusted redirect target.
    if (target.origin !== window.location.origin || !['/order-tracking.html', '/account.html'].includes(target.pathname)) return false;
    window.location.assign(target.pathname + target.search + target.hash);
    return true;
  } catch (_) {
    localStorage.removeItem('postLoginReturnTo');
    return false;
  }
}

async function handleLogin() {
  const username = document.getElementById('loginUsername').value.trim();
  const password = document.getElementById('loginPassword').value;
  const rememberDays = document.getElementById('loginRememberDays')?.value || '';
  const status = document.getElementById('loginStatus');
  if (!status) return;
  status.textContent = '';
  status.className = 'auth-status';

  if (!username || !password) {
    status.textContent = '❌ Username/Email/Phone and password are required.';
    status.className = 'auth-status error';
    return;
  }

  status.textContent = '⏳ Logging in...';
  status.className = 'auth-status';
  status.style.color = '#2563eb';

  try {
    let res, data;

    if (currentLoginType === 'business') {
      res = await fetch('/api/auth/business/login', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ username, password, remember_days: rememberDays })
      });
      data = await res.json();
    } else {
      res = await fetch('/api/auth/customer/login', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ username, password, remember_days: rememberDays })
      });
      data = await res.json();
    }

    if (res.ok && data.success) {
      status.textContent = '✅ Login successful!';
      status.className = 'auth-status success';
      window.customerToken = 'cookie-auth';

      if (data.role === 'business_admin' || data.business_id) {
        localStorage.setItem('businessId', data.business_id);
        localStorage.setItem('businessName', data.business_name);
        localStorage.setItem('businessSlug', data.slug || '');
        localStorage.setItem('currentUser', JSON.stringify({
          name: data.business_name,
          email: data.email,
          role: 'business_admin',
          business_id: data.business_id
        }));

        closeAuthModal();
        showToast('✅ Welcome back, ' + (data.business_name || 'Business') + '!', 'success');
        checkAuthState();
      } else {
        localStorage.setItem('currentUser', JSON.stringify(data.customer || { name: data.name, email: data.email }));
        const loginDestination = new URLSearchParams(window.location.search).get('next');
        if (loginDestination === 'cart') localStorage.setItem('postLoginDestination', 'cart');

        closeAuthModal();
        showToast('✅ Welcome back, ' + (data.customer?.name || data.name || 'User') + '!', 'success');
        checkAuthState();
        if (redirectToPendingServiceConversation()) return;
        const returnToProduct = localStorage.getItem('postLoginReturnToProduct');
        if (returnToProduct && returnToProduct.startsWith('/product-detail.html')) {
          localStorage.removeItem('postLoginReturnToProduct');
          localStorage.setItem('resumePostLoginCartAdd', '1');
          window.location.assign(returnToProduct);
          return;
        }
        if (consumePostLoginReturn()) return;
        if (localStorage.getItem('postLoginDestination') === 'cart') {
          localStorage.removeItem('postLoginDestination');
          window.location.assign('/cart.html');
        }
      }
    } else {
      status.textContent = '❌ ' + (data.error || 'Invalid credentials. Please try again.');
      status.className = 'auth-status error';
    }
  } catch (err) {
    status.textContent = '❌ Network error. Please try again.';
    status.className = 'auth-status error';
    console.error('Login error:', err);
  }
}

